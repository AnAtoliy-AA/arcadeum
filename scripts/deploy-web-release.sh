#!/usr/bin/env bash
# Release-based deploy for the Next.js standalone web app (prod + staging VMs).
#
# Why: the live server used to run straight out of the build tree
# (apps/web/.next/standalone). `next build` wipes `.next` while that server keeps
# writing ISR/route-cache files into it, so builds failed with
#   ENOTEMPTY: directory not empty, rmdir '.../.next/server/route-cache/...'
# and every deploy deleted files from under the running app.
#
# Now the live server only ever runs from an immutable copy:
#
#   ${RELEASES_DIR}/releases/<utc-ts>-<sha>/   one standalone copy per deploy
#   ${RELEASES_DIR}/current -> releases/<id>   switched atomically (mv -T)
#   ${RELEASES_DIR}/start.sh                   pm2 entrypoint (cd current, exec node)
#   ${RELEASES_DIR}/runtime.env                optional, owner-managed runtime env
#
# The build in apps/web/.next is never touched by the running server, so a
# failed build leaves the current release serving untouched. After the switch
# the web process is restarted and health-checked; on failure the symlink is
# rolled back to the previous release and the deploy fails.
#
# Required env: DEPLOY_DIR (git checkout, already reset to the target commit),
#               PM2_NAME (pm2 process name, e.g. arcadeum-web).
# Optional env: WEB_PORT (3000), WEB_HOSTNAME (0.0.0.0), WEB_ENV_FILE (sourced
#               before the build and at runtime), RELEASES_DIR
#               (${DEPLOY_DIR}-releases/web), KEEP_RELEASES (3), HEALTH_PATH (/),
#               HEALTH_TIMEOUT_SECONDS (90).
set -euo pipefail

: "${DEPLOY_DIR:?DEPLOY_DIR is required}"
: "${PM2_NAME:?PM2_NAME is required}"
WEB_PORT="${WEB_PORT:-3000}"
WEB_HOSTNAME="${WEB_HOSTNAME:-0.0.0.0}"
WEB_ENV_FILE="${WEB_ENV_FILE:-}"
RELEASES_DIR="${RELEASES_DIR:-${DEPLOY_DIR}-releases/web}"
KEEP_RELEASES="${KEEP_RELEASES:-3}"
HEALTH_PATH="${HEALTH_PATH:-/}"
HEALTH_TIMEOUT_SECONDS="${HEALTH_TIMEOUT_SECONDS:-90}"

APP_DIR="$DEPLOY_DIR/apps/web"
BUILD_STANDALONE="$APP_DIR/.next/standalone"
RELEASES="$RELEASES_DIR/releases"
CURRENT="$RELEASES_DIR/current"
START_SCRIPT="$RELEASES_DIR/start.sh"
RUNTIME_ENV="$RELEASES_DIR/runtime.env"
HEALTH_URL="http://127.0.0.1:${WEB_PORT}${HEALTH_PATH}"

log() { echo "==> [web-release] $*"; }
die() { echo "ERROR: [web-release] $*" >&2; exit 1; }

ensure_releases_dir() {
  if ! mkdir -p "$RELEASES" 2>/dev/null; then
    sudo mkdir -p "$RELEASES"
    sudo chown -R "$(id -un):$(id -gn)" "$(dirname "$RELEASES_DIR")"
  fi
  # Leftovers from an interrupted deploy.
  rm -rf "$RELEASES"/.tmp-* "$RELEASES_DIR"/.current-* 2>/dev/null || true
}

# Copy a directory tree. Tolerates files vanishing mid-copy (rsync exit 24),
# which can happen when snapshotting a tree a live server still writes to.
copy_tree() {
  local src="$1" dest="$2"
  shift 2
  mkdir -p "$dest"
  if command -v rsync >/dev/null 2>&1; then
    local rc=0
    rsync -a "$@" "$src/" "$dest/" || rc=$?
    if [ "$rc" -ne 0 ] && [ "$rc" -ne 24 ]; then
      return "$rc"
    fi
  else
    cp -a "$src/." "$dest/"
  fi
}

write_start_script() {
  local tmp="$START_SCRIPT.tmp"
  {
    echo '#!/usr/bin/env bash'
    echo '# Generated by scripts/deploy-web-release.sh. Do not edit: rewritten on every deploy.'
    echo 'set -euo pipefail'
    echo 'set -a'
    if [ -n "$WEB_ENV_FILE" ]; then
      printf '[ -f %q ] && source %q\n' "$WEB_ENV_FILE" "$WEB_ENV_FILE"
    fi
    printf '[ -f %q ] && source %q\n' "$RUNTIME_ENV" "$RUNTIME_ENV"
    echo 'set +a'
    printf 'export PORT=%q HOSTNAME=%q\n' "$WEB_PORT" "$WEB_HOSTNAME"
    echo '# Resolve the symlink once: this process stays pinned to its release even'
    echo '# after the next deploy moves `current`.'
    printf 'cd "$(readlink -f %q)/apps/web"\n' "$CURRENT"
    echo 'exec node server.js'
  } >"$tmp"
  chmod +x "$tmp"
  mv -f "$tmp" "$START_SCRIPT"
}

# Atomically point `current` at releases/<id> (relative link, rename(2) swap).
switch_current() {
  local id="$1" tmp="$RELEASES_DIR/.current-$$"
  ln -sfn "releases/$id" "$tmp"
  mv -Tf "$tmp" "$CURRENT"
  log "current -> releases/$id"
}

current_release_id() {
  if [ -L "$CURRENT" ]; then
    basename "$(readlink "$CURRENT")"
  fi
}

# Prints the pm2 exec path of $PM2_NAME (empty if the process does not exist).
# Parses `pm2 jlist` in-process so the process env (secrets) is never printed.
pm2_exec_path() {
  pm2 jlist 2>/dev/null | PM2_NAME="$PM2_NAME" node -e '
    let raw = "";
    process.stdin.on("data", (c) => (raw += c));
    process.stdin.on("end", () => {
      try {
        const start = raw.indexOf("[");
        const list = JSON.parse(start >= 0 ? raw.slice(start) : "[]");
        const proc = list.find((p) => p.name === process.env.PM2_NAME);
        process.stdout.write(proc?.pm2_env?.pm_exec_path ?? "");
      } catch {
        process.stdout.write("");
      }
    });
  '
}

start_or_restart() {
  if [ "$(pm2_exec_path)" = "$START_SCRIPT" ]; then
    pm2 restart "$PM2_NAME"
  else
    pm2 delete "$PM2_NAME" >/dev/null 2>&1 || true
    pm2 start "$START_SCRIPT" --name "$PM2_NAME"
  fi
  pm2 save
}

health_check() {
  local deadline=$((SECONDS + HEALTH_TIMEOUT_SECONDS)) code="000"
  while [ "$SECONDS" -lt "$deadline" ]; do
    code="$(curl -s -o /dev/null -m 10 -w '%{http_code}' "$HEALTH_URL" || true)"
    if [ "$code" -ge 200 ] 2>/dev/null && [ "$code" -lt 400 ]; then
      log "health check OK ($HEALTH_URL -> HTTP $code)"
      return 0
    fi
    sleep 2
  done
  echo "ERROR: [web-release] health check failed ($HEALTH_URL, last HTTP $code)" >&2
  pm2 logs "$PM2_NAME" --lines 40 --nostream || true
  return 1
}

# One-time migration from the legacy layout (pm2 running server.js straight out
# of apps/web/.next/standalone). Snapshot that live build into a release and
# move pm2 onto it BEFORE building, so `next build` can safely wipe `.next`.
migrate_legacy_process() {
  local exec_path
  exec_path="$(pm2_exec_path)"
  if [ -z "$exec_path" ] || [ "$exec_path" = "$START_SCRIPT" ]; then
    return 0
  fi
  log "pm2 '$PM2_NAME' still runs the legacy layout ($exec_path); migrating"
  if [ ! -f "$BUILD_STANDALONE/apps/web/server.js" ]; then
    log "no legacy standalone build found; stopping '$PM2_NAME' until the new release is up"
    pm2 delete "$PM2_NAME" >/dev/null 2>&1 || true
    return 0
  fi

  local id tmp
  id="$(date -u +%Y%m%d%H%M%S)-legacy"
  tmp="$RELEASES/.tmp-$id"
  copy_tree "$BUILD_STANDALONE" "$tmp" \
    --exclude '/apps/web/.next/server/route-cache/' --exclude '/apps/web/.next/cache/'
  # Runtime caches are rebuilt on demand; drop them if cp -a copied them.
  rm -rf "$tmp/apps/web/.next/server/route-cache" "$tmp/apps/web/.next/cache"
  [ -f "$tmp/apps/web/server.js" ] || die "legacy snapshot is missing server.js"
  mv "$tmp" "$RELEASES/$id"

  switch_current "$id"
  write_start_script
  start_or_restart
  if ! health_check; then
    log "legacy snapshot failed to boot; restoring the legacy pm2 process"
    pm2 delete "$PM2_NAME" >/dev/null 2>&1 || true
    pm2 start "$exec_path" --name "$PM2_NAME" --cwd "$(dirname "$exec_path")" || true
    pm2 save || true
    die "migration aborted, legacy process restored; see the manual steps in docs/deploy/web-releases.md"
  fi
  log "legacy process migrated; '$PM2_NAME' now serves releases/$id"
}

build() {
  cd "$DEPLOY_DIR"
  if [ -n "$WEB_ENV_FILE" ]; then
    [ -f "$WEB_ENV_FILE" ] || die "$WEB_ENV_FILE is missing (NEXT_PUBLIC_* values are inlined at build time)"
    # Load env so NEXT_PUBLIC_* are baked into the build.
    set -a
    # shellcheck disable=SC1090
    source "$WEB_ENV_FILE"
    set +a
  fi
  log "building @arcadeum/games-core + web"
  pnpm --filter @arcadeum/games-core build
  (cd "$APP_DIR" && pnpm build)
  [ -f "$BUILD_STANDALONE/apps/web/server.js" ] || die "build did not produce $BUILD_STANDALONE/apps/web/server.js"
}

assemble_release() {
  local id="$1" tmp="$RELEASES/.tmp-$1"
  log "assembling releases/$id"
  copy_tree "$BUILD_STANDALONE" "$tmp"
  cp -a "$APP_DIR/.next/static" "$tmp/apps/web/.next/static"
  if [ -d "$APP_DIR/public" ]; then
    cp -a "$APP_DIR/public" "$tmp/apps/web/public"
  fi
  [ -f "$tmp/apps/web/server.js" ] || die "assembled release is missing server.js"
  mv "$tmp" "$RELEASES/$id"
}

# Keep the newest $KEEP_RELEASES releases plus whatever `current` and the
# rollback target point at; delete the rest.
prune_releases() {
  local keep_a="$1" keep_b="${2:-}" n=0 entry
  while IFS= read -r entry; do
    [ -n "$entry" ] || continue
    n=$((n + 1))
    if [ "$n" -le "$KEEP_RELEASES" ] || [ "$entry" = "$keep_a" ] || [ "$entry" = "$keep_b" ]; then
      continue
    fi
    log "pruning old release $entry"
    rm -rf "${RELEASES:?}/$entry"
  done < <(find "$RELEASES" -mindepth 1 -maxdepth 1 -type d ! -name '.*' -exec basename {} \; | sort -r)
}

main() {
  [ -d "$APP_DIR" ] || die "$APP_DIR not found"
  ensure_releases_dir
  migrate_legacy_process

  build

  local id previous
  id="$(date -u +%Y%m%d%H%M%S)-$(git -C "$DEPLOY_DIR" rev-parse --short HEAD)"
  previous="$(current_release_id || true)"
  assemble_release "$id"

  switch_current "$id"
  write_start_script
  start_or_restart

  if ! health_check; then
    if [ -n "$previous" ] && [ -d "$RELEASES/$previous" ]; then
      log "rolling back to releases/$previous"
      switch_current "$previous"
      start_or_restart
      health_check || true
    fi
    die "new release $id failed its health check"
  fi

  prune_releases "$id" "$previous"
  log "deployed releases/$id (rollback target: ${previous:-none})"
  pm2 list "$PM2_NAME" || true
}

main "$@"
